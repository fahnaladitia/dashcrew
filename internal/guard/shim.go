package guard

import (
	"crypto/sha256"
	"encoding/hex"
	"io/fs"
	"path"
	"path/filepath"
	"sort"
	"strings"

	"github.com/fahnaladitia/dashcrew"
)

// ShimPath is the committed hook entry; it runs the guard installed for the project's guard source.
const ShimPath = ".ai/bin/guard"

// SourceHash is the lock's `guard_source`: the hash of the Dart guard sources (`bin/guard.dart`, then every file
// of `lib/src/guard/` by path), joined by NUL. Stage G7 replaces it with the dashcrew version.
func SourceHash() (string, error) {
	sources := []string{"bin/guard.dart"}
	entries, err := fs.ReadDir(dashcrew.DartGuardSourceFS, "lib/src/guard")
	if err != nil {
		return "", err
	}
	var guardFiles []string
	for _, entry := range entries {
		if !entry.IsDir() {
			guardFiles = append(guardFiles, path.Join("lib/src/guard", entry.Name()))
		}
	}
	sort.Strings(guardFiles)
	sources = append(sources, guardFiles...)
	contents := make([]string, len(sources))
	for i, source := range sources {
		data, err := fs.ReadFile(dashcrew.DartGuardSourceFS, source)
		if err != nil {
			return "", err
		}
		contents[i] = string(data)
	}
	sum := sha256.Sum256([]byte(strings.Join(contents, "\x00")))
	return hex.EncodeToString(sum[:]), nil
}

// Shim is `.ai/bin/guard`, the committed entry every agent hook calls: it runs this machine's guard for hash,
// installs it on demand when `dashcrew` is on PATH, and otherwise allows the call with a note on stderr.
func Shim(hash string) string {
	return `#!/bin/sh
# Generated by dashcrew sync. Hooks call this file; it runs the guard compiled for this project.
guard="${DASHCREW_HOME:-$HOME/.dashcrew}/guard/` + hash[:16] + `/guard"
if [ ! -x "$guard" ] && command -v dashcrew >/dev/null 2>&1; then
  dashcrew guard install --expect ` + hash + ` </dev/null >/dev/null 2>&1
fi
if [ -x "$guard" ]; then
  exec "$guard" "$@"
fi
cat >/dev/null
echo "[dashcrew guard] not installed on this machine: run dashcrew sync" >&2
exit 0
`
}

// DefaultHome is `DASHCREW_HOME`, else `<home>/.dashcrew`; false when no home directory is known.
func DefaultHome(environment map[string]string) (string, bool) {
	if override := environment["DASHCREW_HOME"]; override != "" {
		return override, true
	}
	user, ok := environment["HOME"]
	if !ok {
		user, ok = environment["USERPROFILE"]
	}
	if !ok {
		return "", false
	}
	return filepath.Join(user, ".dashcrew"), true
}

// BinaryPath is where the guard for hash lives under home: the folder is the hash's first 16 characters.
func BinaryPath(home, hash string) string {
	return filepath.Join(home, "guard", hash[:min(16, len(hash))], "guard")
}
