package knowledge

import (
	"errors"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// PageDirs are the folders that hold reviewed pages.
var PageDirs = []string{"features", "repos"}

const (
	pagesHeading = "## Pages"
	indexNote    = "Generated by `dashcrew knowledge review` from the pages below; edit the pages, not this list."
	noRepo       = "(no repo)"
	noTag        = "(no tag)"
)

var (
	comment       = regexp.MustCompile(`<!--.*?-->`)
	sentenceEnd   = regexp.MustCompile(`[.!?](\s|$)`)
	nonParagraph  = regexp.MustCompile(`^\s*([-*+>|]|[0-9]+[.)]\s)`)
	pagesSection  = regexp.MustCompile(`(?m)^## Pages[ \t]*$`)
	collapseSpace = regexp.MustCompile(`\s+`)
)

// IndexedPage is one page as the README index lists it.
type IndexedPage struct {
	// Path is slash-separated and relative to the clone, such as `features/share.md`.
	Path  string
	Page  Page
	Title string
}

// Pages reads every `*.md` page in features/ and repos/ of the clone, sorted by path.
func Pages(clone string) ([]IndexedPage, error) {
	var out []IndexedPage
	for _, dir := range PageDirs {
		entries, err := os.ReadDir(filepath.Join(clone, dir))
		if errors.Is(err, fs.ErrNotExist) {
			continue
		}
		if err != nil {
			return nil, err
		}
		for _, entry := range entries {
			if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".md") {
				continue
			}
			data, err := os.ReadFile(filepath.Join(clone, dir, entry.Name()))
			if err != nil {
				return nil, err
			}
			page := Parse(string(data))
			path := dir + "/" + entry.Name()
			title := page.Title
			if title == "" {
				title = path
			}
			out = append(out, IndexedPage{Path: path, Page: page, Title: title})
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Path < out[j].Path })
	return out, nil
}

// NewestVerified is the latest date among the page's verified markers; empty when it has none.
func NewestVerified(page Page) string {
	newest := ""
	for _, v := range page.Verified {
		if v.Date > newest {
			newest = v.Date
		}
	}
	return newest
}

// FirstSentence is the first sentence of the page's first paragraph, without HTML comments; headings, lists,
// quotes, tables and fenced code are skipped. It always ends with punctuation; empty when the page has no paragraph.
func FirstSentence(page Page) string {
	var paragraph []string
	openFence := ""
	for _, line := range strings.Split(page.Body, "\n") {
		if match := fence.FindStringSubmatch(line); match != nil {
			if openFence == "" {
				openFence = match[1]
			} else if openFence == match[1] {
				openFence = ""
			}
			if len(paragraph) > 0 {
				break
			}
			continue
		}
		text := strings.TrimSpace(comment.ReplaceAllString(line, ""))
		switch {
		case openFence != "":
		case text == "" || heading.MatchString(line) || nonParagraph.MatchString(line):
			if len(paragraph) > 0 {
				return sentence(paragraph)
			}
		default:
			paragraph = append(paragraph, text)
		}
	}
	return sentence(paragraph)
}

func sentence(paragraph []string) string {
	text := collapseSpace.ReplaceAllString(strings.Join(paragraph, " "), " ")
	if text == "" {
		return ""
	}
	if loc := sentenceEnd.FindStringIndex(text); loc != nil {
		return text[:loc[0]+1]
	}
	return text + "."
}

// UpdateReadme is readme with its `## Pages` section, up to the end of the file, replaced by the index of the
// clone's pages, grouped by repo then tag; a page with several repos or tags is listed under each. A readme
// without that section gets it appended.
func UpdateReadme(readme, clone string) (string, error) {
	pages, err := Pages(clone)
	if err != nil {
		return "", err
	}
	readme = strings.ReplaceAll(readme, "\r\n", "\n")
	head := strings.TrimRight(readme, "\n")
	if loc := pagesSection.FindStringIndex(readme); loc != nil {
		head = strings.TrimRight(readme[:loc[0]], "\n")
	}
	var b strings.Builder
	if head != "" {
		b.WriteString(head + "\n\n")
	}
	b.WriteString(pagesHeading + "\n\n")
	if len(pages) == 0 {
		b.WriteString("None reviewed yet.\n")
		return b.String(), nil
	}
	b.WriteString(indexNote + "\n")

	groups := map[string]map[string][]IndexedPage{}
	for _, page := range pages {
		repos, tags := page.Page.Repos, page.Page.Tags
		if len(repos) == 0 {
			repos = []string{noRepo}
		}
		if len(tags) == 0 {
			tags = []string{noTag}
		}
		for _, repo := range repos {
			if groups[repo] == nil {
				groups[repo] = map[string][]IndexedPage{}
			}
			for _, tag := range tags {
				groups[repo][tag] = append(groups[repo][tag], page)
			}
		}
	}
	for _, repo := range sortedKeys(groups, noRepo) {
		b.WriteString("\n### " + repo + "\n")
		for _, tag := range sortedKeys(groups[repo], noTag) {
			b.WriteString("\n#### " + tag + "\n\n")
			for _, page := range groups[repo][tag] {
				b.WriteString(indexLine(page) + "\n")
			}
		}
	}
	return b.String(), nil
}

func indexLine(page IndexedPage) string {
	line := "- [" + page.Title + "](" + page.Path + "):"
	if first := FirstSentence(page.Page); first != "" {
		line += " " + first
	}
	if newest := NewestVerified(page.Page); newest != "" {
		return line + " Verified " + newest + "."
	}
	return line + " Not verified."
}

// sortedKeys sorts the keys with last, when present, at the end.
func sortedKeys[V any](m map[string]V, last string) []string {
	keys := make([]string, 0, len(m))
	for key := range m {
		if key != last {
			keys = append(keys, key)
		}
	}
	sort.Strings(keys)
	if _, ok := m[last]; ok {
		keys = append(keys, last)
	}
	return keys
}
